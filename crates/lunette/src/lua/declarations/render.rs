//! Writing `lua/lunette/init.luau` out.
//!
//! The output is already StyLua-formatted, because `stylua --check lua` is one
//! of the standing checks.

use std::fmt::Write as _;

use lunette_compositor::protocol::PointerButton;

use crate::{
    events::{payload_records, subscription_functions},
    lua::{
        Claim, ErrorEvent, Monitor, Output, Process, Seat, Sink, Spawn, Window,
        claim::ClaimLayer,
        declarations::{
            Handle, NullTexture, Property, PropertyType, Record, Recorded, Textured, Type, Typed,
            collect,
        },
        module_functions,
        output::{NewOutput, SetMode},
        seat::{NewSeat, Stroke},
        values::PointerButtonName,
    },
};

/// Renders the whole file.
#[must_use]
pub fn render() -> String {
    let mut out = String::from(HEADER);
    let items = surface();

    render_alias(
        &mut out,
        &Textured::luau(),
        "The handles that carry pixels. A caller with one and no interest in which reads the \
         fields both have and calls `getTexture`, which is why that method names this as its \
         receiver on both.",
        &textured(&items),
    );

    render_alias(
        &mut out,
        &PointerButtonName::luau(),
        "Which pointer button an event names. The runtime refuses anything else.",
        &Type::literals(PointerButton::NAMES),
    );

    for item in &items {
        match item {
            Item::Handle(handle) => render_handle(&mut out, handle),
            Item::Record(record) => render_record(&mut out, record),
        }
    }

    render_module(&mut out);
    out.push('\n');
    out.push_str(FOOTER);

    out
}

/// One declaration in the generated file.
enum Item {
    Handle(Handle),
    Record(Record),
}

/// Everything below the aliases, in the order the file states it: a handle
/// beside the option table its constructor takes.
fn surface() -> Vec<Item> {
    let mut items = vec![
        Item::Handle(collect::<Sink<NullTexture>>()),
        Item::Handle(collect::<Window<NullTexture>>()),
        Item::Handle(collect::<Monitor<NullTexture>>()),
        Item::Handle(collect::<Process<NullTexture>>()),
        Item::Record(Stroke::RECORD),
        Item::Record(NewSeat::RECORD),
        Item::Handle(collect::<Seat<NullTexture>>()),
        Item::Record(SetMode::RECORD),
        Item::Record(NewOutput::RECORD),
        Item::Handle(collect::<Output<NullTexture>>()),
        Item::Record(Spawn::RECORD),
        Item::Record(ClaimLayer::RECORD),
        Item::Handle(collect::<Claim<NullTexture>>()),
        Item::Record(ErrorEvent::RECORD),
    ];
    // The tables the `lovr.lun*` callbacks are called with. They are exported
    // from the module rather than declared beside the callbacks, because a
    // definitions file declares globals and cannot name a module's types: the
    // handles a payload carries are `Window` and `Claim`, which exist only
    // here. `docs/lua-api.md` records what that means for a configuration.
    items.extend(payload_records().into_iter().map(Item::Record));
    items
}

const HEADER: &str = "\
-- The `lunette` module as the type checker sees it.
--
-- Generated by `cargo run -p lunette-generate-definitions` from the Rust
-- registration surface. A change belongs beside the registration, in
-- `crates/lunette/src/lua/`, not here.
--
-- At runtime the module is the table the host registers in `package.preload`,
-- so nothing below is executed. It exists because Luau resolves a require to a
-- file on disk, and a definitions file can only declare globals.
";

const FOOTER: &str = "return (nil :: any) :: Lunette\n";

/// Where a comment wraps, which is where the prose in the tree already sits.
const COLUMNS: usize = 80;

/// Renders one `export type`, naming it by the type the Rust side declares
/// itself as rather than by a second spelling written here.
fn render_alias(out: &mut String, alias: &Type, doc: &str, definition: &Type) {
    out.push('\n');
    render_doc(out, doc, "");
    let _ = writeln!(out, "export type {alias} = {definition}");
}

/// The handles that carry pixels.
///
/// Read from the surface rather than listed: a handle carries pixels exactly
/// when one of its methods names `Textured` as its receiver, which is what
/// `getTexture` does, so the union follows from the declarations instead of
/// being a second statement of which handles have one.
fn textured(items: &[Item]) -> Type {
    let marker = Textured::luau();
    Type::Union(
        items
            .iter()
            .filter_map(|item| match item {
                Item::Handle(handle) => handle
                    .methods
                    .iter()
                    .any(|method| {
                        matches!(
                            &method.ty,
                            Type::Function { receiver: Some(receiver), .. }
                                if **receiver == marker
                        )
                    })
                    .then_some(Type::Named(handle.spec.name)),
                Item::Record(_) => None,
            })
            .collect(),
    )
}

/// Renders a handle as one table, or as the arms of a discriminated union and
/// the intersection that joins them.
fn render_handle(out: &mut String, handle: &Handle) {
    let name = handle.spec.name;
    let discriminated = !handle.spec.variants.is_empty();

    out.push('\n');
    render_doc(out, handle.spec.doc, "");
    if discriminated {
        let _ = writeln!(out, "type {name}Fields = {{");
    } else {
        let _ = writeln!(out, "export type {name} = {{");
    }

    for field in &handle.fields {
        if let PropertyType::Same(ty) = &field.ty {
            render_doc(out, field.doc, "  ");
            let _ = writeln!(out, "  read {}: {ty},", field.name);
        }
    }
    for method in &handle.methods {
        render_doc(out, method.doc, "  ");
        let _ = writeln!(out, "  read {}: {},", method.name, method.ty);
    }
    out.push_str("}\n");

    for (arm, variant) in handle.spec.variants.iter().enumerate() {
        let fields: Vec<String> = handle
            .fields
            .iter()
            .filter_map(|field| arm_type(field, arm))
            .collect();
        let _ = writeln!(out, "\ntype {variant} = {{ {} }}", fields.join(", "));
    }

    if discriminated {
        let arms = handle.spec.variants.join(" | ");
        let _ = writeln!(out, "\nexport type {name} = {name}Fields & ({arms})");
    }
}

/// What one arm says about a field, where the arms disagree.
fn arm_type(field: &Property, arm: usize) -> Option<String> {
    match &field.ty {
        PropertyType::Same(_) => None,
        PropertyType::PerVariant(types) => Some(format!("read {}: {}", field.name, types[arm])),
    }
}

fn render_record(out: &mut String, record: &Record) {
    out.push('\n');
    render_doc(out, record.doc, "");
    let _ = writeln!(out, "export type {} = {{", record.name);
    for field in record.fields {
        render_doc(out, field.doc, "  ");
        let _ = writeln!(out, "  {}: {},", field.name, (field.ty)());
    }
    out.push_str("}\n");
}

fn render_module(out: &mut String) {
    out.push_str("\nexport type Lunette = {\n");
    for function in module_functions::<NullTexture>()
        .into_iter()
        .chain(subscription_functions::<NullTexture>())
    {
        render_doc(out, function.spec.doc, "  ");
        let _ = writeln!(out, "  read {}: {},", function.spec.name, (function.ty)());
    }
    out.push_str("}\n");
}

/// Writes prose as Lua comments at `indent`, wrapped to [`COLUMNS`].
///
/// A declaration states its prose as one line; the wrapping is decided here, so
/// reflowing the file is not an edit to every declaration in it.
fn render_doc(out: &mut String, doc: &str, indent: &str) {
    let width = COLUMNS.saturating_sub(indent.len() + "-- ".len());
    let mut line = String::new();

    for word in doc.split_whitespace() {
        if !line.is_empty() && line.len() + 1 + word.len() > width {
            let _ = writeln!(out, "{indent}-- {line}");
            line.clear();
        }
        if !line.is_empty() {
            line.push(' ');
        }
        line.push_str(word);
    }

    if !line.is_empty() {
        let _ = writeln!(out, "{indent}-- {line}");
    }
}
